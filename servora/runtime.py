from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path


class PortableStorageMovedError(RuntimeError):
    """Raised when the portable root was moved and storage.conf still points
    at the old absolute location while real data exists there."""


def choose_storage_driver(root: Path | None = None) -> tuple[str, str | None]:
    """Pick a portable storage driver for *root* without touching system state.

    Returns ``(driver, mount_program)``.

    Rules (verified against Podman 4.x behaviour):
      * ``overlay`` + kernel support works only rootful; it is fast and space
        efficient, so prefer it when we are effectively uid 0 and can mount
        overlayfs.
      * Rootless with fuse-overlayfs available: use ``overlay`` with an
        explicit ``mount_program`` (Podman requires the option to live under
        ``[storage.options.overlay]``).
      * Otherwise fall back to ``vfs``: universally supported but slow and it
        duplicates every layer per container — reported to the caller so the
        trade-off is visible.
    """
    euid = os.geteuid() if hasattr(os, "geteuid") else 1
    fuse = shutil.which("fuse-overlayfs")

    if euid == 0:
        # Try a real kernel overlay mount in a throwaway directory under root
        # (or /tmp). Only succeed if we can actually mount AND unmount.
        base = Path(root) if root else Path("/tmp")
        probe = base / ".servora-overlay-probe"
        upper = probe / "u"
        lower = probe / "l"
        work = probe / "w"
        merged = probe / "m"
        try:
            for d in (upper, lower, work, merged):
                d.mkdir(parents=True, exist_ok=True)
            result = subprocess.run(
                ["mount", "-t", "overlay", "overlay", "-o",
                 f"lowerdir={lower},upperdir={upper},workdir={work}", str(merged)],
                capture_output=True, text=True, check=False,
            )
            if result.returncode == 0:
                subprocess.run(["umount", str(merged)], capture_output=True, check=False)
                return ("overlay", None)
        except OSError:
            pass
        finally:
            shutil.rmtree(probe, ignore_errors=True)
        # Rootful but no kernel overlay: fuse fallback if present.
        return ("overlay", fuse) if fuse else ("vfs", None)

    # Rootless: kernel overlay is not available; need fuse-overlayfs.
    return ("overlay", fuse) if fuse else ("vfs", None)


class Runtime:
    """Filesystem layout for Servora.

    Portable mode keeps all Servora-owned state under ``root``. User mode
    defaults to ~/.servora. Podman is never silently migrated.
    """

    def __init__(self, root: str | Path | None = None, mode: str = "user"):
        if mode not in {"user", "portable"}:
            raise ValueError("mode must be 'user' or 'portable'")
        self.mode = mode
        self.root = Path(root) if root else Path.home() / ".servora"
        self.config = self.root / "config"
        self.metadata = self.root / "metadata"
        self.logs = self.root / "logs"
        self.podman = self.root / "podman"
        self.apps = self.root / "apps"
        self.backups = self.root / "backups"

    @property
    def config_file(self) -> Path:
        return self.config / "servora.json"

    @property
    def storage_conf(self) -> Path:
        return self.podman / "storage.conf"

    @property
    def storage_root(self) -> Path:
        return self.podman / "storage"

    @property
    def run_root(self) -> Path:
        return self.podman / "runroot"

    def initialize(self) -> None:
        for path in (
            self.config, self.metadata, self.logs, self.podman,
            self.apps, self.backups,
        ):
            path.mkdir(parents=True, exist_ok=True)
        if not self.config_file.exists():
            self.config_file.write_text(
                json.dumps({"version": 1, "mode": self.mode}, indent=2) + "\n",
                encoding="utf-8",
            )
        # In portable mode, materialize the private Podman storage layout so
        # CONTAINERS_STORAGE_CONF points at an existing file and graphroot /
        # runroot directories exist before any podman invocation.
        if self.mode == "portable":
            self._ensure_portable_storage()

    def _render_storage_conf(self, driver: str, mount_program: str | None) -> str:
        lines = [
            "# Generated by Servora for portable Podman storage.",
            "# This file replaces containers.conf entirely via",
            "# CONTAINERS_STORAGE_CONF; keep required sections here.",
            "[storage]",
            f'  driver = "{driver}"',
            f'  graphroot = "{self.storage_root}"',
            f'  runroot = "{self.run_root}"',
        ]
        if driver == "overlay" and mount_program:
            lines += [
                "[storage.options.overlay]",
                f'  mount_program = "{mount_program}"',
            ]
        lines.append("")
        return "\n".join(lines)

    def _ensure_portable_storage(self) -> None:
        self.storage_root.mkdir(parents=True, exist_ok=True)
        self.run_root.mkdir(parents=True, exist_ok=True)

        conf_path = self.storage_conf
        moved = False
        if conf_path.exists():
            text = conf_path.read_text(encoding="utf-8")
            expected_graphroot = str(self.storage_root)
            if f'graphroot = "{expected_graphroot}"' not in text:
                # The portable root was moved (or the conf was written for a
                # different location). Never touch data automatically.
                old_graphroot = _parse_toml_string(text, "storage", "graphroot")
                has_data = (
                    old_graphroot
                    and Path(old_graphroot).exists()
                    and _dir_has_entries(Path(old_graphroot))
                )
                if has_data:
                    raise PortableStorageMovedError(
                        "Servora portable root was moved but Podman storage.conf "
                        f"still points at '{old_graphroot}' which contains data. "
                        "Nothing was migrated automatically. Move the directory "
                        "back, or run Runtime.relocate_portable_storage(confirm=False) "
                        "to inspect, then confirm=True to regenerate configuration "
                        "for a fresh empty storage (the old data is left untouched)."
                    )
                # Old location absent/empty: safe to rewrite config in place.
                driver, mount_program = choose_storage_driver(self.podman)
                conf_path.write_text(
                    self._render_storage_conf(driver, mount_program), encoding="utf-8"
                )
                moved = True
            # else: config already matches current root; keep user edits intact.
        else:
            driver, mount_program = choose_storage_driver(self.podman)
            conf_path.write_text(
                self._render_storage_conf(driver, mount_program), encoding="utf-8"
            )
            moved = True

        marker = self.podman / "storage-location.json"
        if moved or not marker.exists():
            marker.write_text(
                json.dumps(
                    {
                        "version": 1,
                        "graphroot": str(self.storage_root),
                        "runroot": str(self.run_root),
                        "storage_conf": str(conf_path),
                    },
                    indent=2,
                ) + "\n",
                encoding="utf-8",
            )

    def relocate_portable_storage(self, confirm: bool = False) -> dict:
        """Safe recovery flow after the portable root was moved.

        - Reports where the old configuration points and whether it holds data.
        - Never moves, deletes, or overwrites existing storage data.
        - With ``confirm=True`` and no data at the old location (or the old
          location missing), regenerates storage.conf for the new location.
        - If the old location contains data, raises unless the operator has
          dealt with the old data externally first.
        """
        conf_path = self.storage_conf
        report = {
            "current_root": str(self.root),
            "storage_conf_exists": conf_path.exists(),
            "old_graphroot": None,
            "old_location_exists": False,
            "old_location_has_data": False,
            "relocated": False,
        }
        if not conf_path.exists():
            self._ensure_portable_storage()
            report["relocated"] = True
            return report

        text = conf_path.read_text(encoding="utf-8")
        old_graphroot = _parse_toml_string(text, "storage", "graphroot")
        report["old_graphroot"] = old_graphroot
        if old_graphroot:
            old_path = Path(old_graphroot)
            report["old_location_exists"] = old_path.exists()
            report["old_location_has_data"] = old_path.exists() and _dir_has_entries(old_path)

        if str(self.storage_root) in text:
            return report  # already consistent

        if report["old_location_has_data"]:
            raise PortableStorageMovedError(
                f"Old portable storage at '{old_graphroot}' contains data. "
                "Refusing to reconfigure automatically to avoid data loss. "
                "Archive or remove that directory manually, then call "
                "relocate_portable_storage(confirm=True)."
            )
        if not confirm:
            raise PortableStorageMovedError(
                "storage.conf does not match the current portable root. "
                "Call relocate_portable_storage(confirm=True) to regenerate "
                "the configuration for the new location."
            )
        driver, mount_program = choose_storage_driver(self.podman)
        conf_path.write_text(
            self._render_storage_conf(driver, mount_program), encoding="utf-8"
        )
        self._ensure_portable_storage()
        report["relocated"] = True
        return report

    def podman_environment(self) -> dict[str, str]:
        """Return environment overrides without changing system Podman state.

        Only ``CONTAINERS_STORAGE_CONF`` affects Podman: it replaces the whole
        containers.conf lookup, which is why the generated file must also keep
        every storage setting (driver, graphroot, runroot, mount_program).
        ``CONTAINERS_GRAPHROOT``/``CONTAINERS_RUNROOT`` are *not* honoured by
        Podman (verified on Podman 4.3.1) but are kept as informational values
        so Servora tooling and tests can assert where the data lives; they are
        always in sync with the paths written into storage.conf.
        """
        return {
            "CONTAINERS_STORAGE_CONF": str(self.storage_conf),
            "CONTAINERS_GRAPHROOT": str(self.storage_root),
            "CONTAINERS_RUNROOT": str(self.run_root),
        }


def _parse_toml_string(text: str, table: str, key: str) -> str | None:
    """Very small TOML reader for `key = "value"` inside `[table]` blocks."""
    in_table = False
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("[") and line.endswith("]"):
            in_table = line[1:-1].strip('"') == table
            continue
        if in_table and line.startswith(f"{key}"):
            _, _, value = line.partition("=")
            value = value.strip().strip('"')
            return value or None
    return None


def _dir_has_entries(path: Path) -> bool:
    try:
        return any(p for p in path.iterdir())
    except (PermissionError, FileNotFoundError):
        return False
